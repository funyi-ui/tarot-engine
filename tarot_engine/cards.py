def _build_deck() -> Tuple[Card, ...]:
    deck: List[Card] = []
    for i, (en, ko, up, rev) in enumerate(_MAJOR):
        deck.append(Card(i, en, ko, "major", None, None, _kw(up), _kw(rev)))
    next_id = len(_MAJOR)
    for suit_key, suit_en, suit_ko, meanings in _SUITS:
        assert len(meanings) == len(_RANKS), suit_key
        for (rank_key, rank_en, rank_ko), (up, rev) in zip(_RANKS, meanings):
            deck.append(
                Card(
                    next_id,
                    f"{rank_en} of {suit_en}",
                    f"{suit_ko} {rank_ko}",
                    "minor",
                    suit_key,
                    rank_key,
                    _kw(up),
                    _kw(rev),
                )
            )
            next_id += 1
    return tuple(deck)


DECK: Tuple[Card, ...] = _build_deck()
CARDS_BY_ID: Dict[int, Card] = {c.id: c for c in DECK}


def find_card(query: str) -> Card:
    """id(숫자), 영문명, 한글명으로 카드를 찾는다. 없으면 KeyError."""
    q = query.strip()
    if q.isdigit() and int(q) in CARDS_BY_ID:
        return CARDS_BY_ID[int(q)]
    lowered = q.lower()
    for card in DECK:
        if card.name_en.lower() == lowered or card.name_ko == q:
            return card
    raise KeyError(f"카드를 찾을 수 없습니다: {query!r}")
